"""Run the examples in the documentation pages.

``api.rst`` is hand-written rather than generated by autodoc, so nothing
otherwise connects it to the code and it can drift silently.  It had: four
examples with no expected output recorded at all, and one asserting a value
that depends on how the extension was compiled.

Only pages that currently pass are listed.  ``python_ex.rst`` has 20 failing
examples -- some from unseeded ``np.random``, some from numpy 2.x repr changes,
and two from 0.2.0 replacing a ``print`` with a warning and adding a key to the
approximation payload -- and joins this list once they are fixed.
"""

import doctest
import pathlib
import warnings

import pytest

DOCS = pathlib.Path(__file__).resolve().parent.parent / "docs" / "source"
RST_PAGES = ["api.rst"]


@pytest.mark.skipif(not DOCS.is_dir(), reason="docs/ not present (sdist install)")
@pytest.mark.parametrize("page", RST_PAGES)
def test_documentation_examples(page):
    path = DOCS / page
    assert path.is_file(), f"{page} is missing"
    with warnings.catch_warnings():
        # The approximation examples warn on purpose; that is the documented
        # behaviour, and it is asserted in test_zagar.py.
        warnings.simplefilter("ignore", RuntimeWarning)
        result = doctest.testfile(
            str(path),
            module_relative=False,
            optionflags=doctest.NORMALIZE_WHITESPACE,
            verbose=False,
        )
    assert result.failed == 0, (
        f"{result.failed} of {result.attempted} examples in {page} failed; "
        "run `python -m doctest docs/source/" + page + "` to see them"
    )
    assert result.attempted > 50, (
        f"only {result.attempted} examples found in {page}; the parser may "
        "have stopped early"
    )
